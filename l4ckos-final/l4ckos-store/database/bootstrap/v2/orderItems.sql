CREATE TABLE `orderItems` (
  `id` int NOT NULL AUTO_INCREMENT,
  `orderId` int NOT NULL,
  `productId` int NOT NULL,
  `quantity` int NOT NULL,
  `unitPrice` int NOT NULL,
  `createdAt` timestamp NOT NULL DEFAULT (now()),
  `variantId` int DEFAULT NULL,
  `productName` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `variantName` varchar(120) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `sku` varchar(120) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `size` varchar(60) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `color` varchar(60) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `totalPrice` int DEFAULT NULL,
  `imageUrl` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `salesModeAtPurchase` enum('STOCK','PREORDER') COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'STOCK',
  `productionBatchId` int DEFAULT NULL,
  `productionBatchNameAtPurchase` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `estimatedShippingStartAtPurchase` timestamp NULL DEFAULT NULL,
  `estimatedShippingEndAtPurchase` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `orderItems_orderId_idx` (`orderId`),
  KEY `orderItems_productId_idx` (`productId`),
  KEY `orderItems_variantId_idx` (`variantId`),
  KEY `orderItems_batch_order` (`productionBatchId`,`orderId`),
  CONSTRAINT `order_items_order_fk` FOREIGN KEY (`orderId`) REFERENCES `orders` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `orderItems_batch_fk` FOREIGN KEY (`productionBatchId`) REFERENCES `productionBatches` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `order_items_quantity_positive_chk` CHECK ((`quantity` > 0)),
  CONSTRAINT `order_items_total_price_nonnegative_chk` CHECK (((`totalPrice` is null) or (`totalPrice` >= 0))),
  CONSTRAINT `order_items_unit_price_nonnegative_chk` CHECK ((`unitPrice` >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
