CREATE TABLE `payments` (
  `id` int NOT NULL AUTO_INCREMENT,
  `orderId` int NOT NULL,
  `provider` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'asaas',
  `providerPaymentId` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `providerCustomerId` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `billingType` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `amount` int NOT NULL,
  `status` enum('pending','confirmed','received','failed','overdue','cancelled','partially_refunded','refunded','chargeback') CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'pending',
  `creationStatus` enum('not_started','creating','created','unknown','failed') CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'not_started',
  `creationLeaseExpiresAt` timestamp NULL DEFAULT NULL,
  `externalReference` varchar(191) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  `invoiceUrl` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `bankSlipUrl` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `pixQrCode` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `pixCopyPaste` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci,
  `digitableLine` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `confirmedAt` timestamp NULL DEFAULT NULL,
  `receivedAt` timestamp NULL DEFAULT NULL,
  `refundedAt` timestamp NULL DEFAULT NULL,
  `paidAmount` int NOT NULL DEFAULT '0',
  `refundedAmount` int NOT NULL DEFAULT '0',
  `netAmount` int NOT NULL DEFAULT '0',
  `statusSource` enum('provider','reconciliation','manual','system') CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'provider',
  `financialIssue` varchar(191) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `financialIssueAt` timestamp NULL DEFAULT NULL,
  `manualConfirmedAt` timestamp NULL DEFAULT NULL,
  `manualConfirmedBy` int DEFAULT NULL,
  `manualReason` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `manualEvidence` varchar(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `payments_orderId_unique` (`orderId`),
  UNIQUE KEY `payments_externalReference_unique` (`externalReference`),
  UNIQUE KEY `payments_providerPaymentId_unique` (`providerPaymentId`),
  KEY `payments_status_idx` (`status`),
  CONSTRAINT `payments_order_fk` FOREIGN KEY (`orderId`) REFERENCES `orders` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `payments_amount_nonnegative_chk` CHECK ((`amount` >= 0)),
  CONSTRAINT `payments_net_amount_nonnegative_chk` CHECK ((`netAmount` >= 0)),
  CONSTRAINT `payments_paid_amount_nonnegative_chk` CHECK ((`paidAmount` >= 0)),
  CONSTRAINT `payments_refunded_amount_nonnegative_chk` CHECK ((`refundedAmount` >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
